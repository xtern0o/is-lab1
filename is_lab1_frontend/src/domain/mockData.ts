import type { EntityCollections, EntityRecord } from './types'

function records(keys: string[], values: string[][]): EntityRecord[] {
  return values.map(
    (row) => Object.fromEntries(keys.map((key, i) => [key, row[i] ?? ''])) as EntityRecord,
  )
}

